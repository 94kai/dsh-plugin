import { mkdir, readFile, writeFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
// Explicit allowlist: never scan the workspace or include .local/private files.
const entries = [
  ['home', 'client.js'],
  ['shortcuts', 'client.js'],
  ['network-speed', 'client-entry.js'],
  ['outing-checklist', 'client.js'],
  ['media', 'client.js'],
];
const viewSources = Object.fromEntries(await Promise.all(['music', 'xiaoai'].map(async name => [name, await readFile(new URL(`features/${name}/view.js`, root), 'utf8')])));
const homeStartup = await readFile(new URL('features/home/startup.js', root), 'utf8');
const factories = [];
for (const [name, file] of entries) {
  let source = await readFile(new URL(`features/${name}/${file}`, root), 'utf8');
  if (name === 'home') {
    const marker = '/* HOME_STARTUP */';
    if (source.split(marker).length !== 2) throw new Error('Expected one home startup marker');
    source = source.replace(marker, () => homeStartup);
  }
  if (name === 'media') {
    for (const feature of ['music', 'xiaoai']) {
      const marker = `/* ${feature.toUpperCase()}_VIEW */`;
      if (source.split(marker).length !== 2) throw new Error('Expected one view marker');
      source = source.replace(marker, () => viewSources[feature]);
    }
  }
  if (name === 'network-speed') {
    const marker = '/* MEASUREMENT_ENGINE */';
    if (source.split(marker).length !== 2) throw new Error('Expected one measurement marker');
    const engine = (await readFile(new URL('features/network-speed/measurement.js', root), 'utf8')).replace(/^export /gm, '');
    source = source.replace(marker, () => engine);
  }
  // Feature sources retain independently testable loader factories. The deployed
  // artifact registers only the aggregate module, not the legacy package IDs.
  const prefix = 'window.__ModuleLoader__.load(';
  if (!source.startsWith(prefix) || !source.trimEnd().endsWith(');')) throw new Error(`Invalid client factory: ${name}`);
  factories.push(`(${source.trimEnd().slice(prefix.length, -2)}).factory(require)`);
}
const output = `// Generated by npm run build. Edit features/, never this artifact.\nwindow.__ModuleLoader__.load({\n  id: '@local/pocket-kit',\n  factory(require) {\n    const plugins = [\n${factories.join(',\n')}\n    ];\n    return {\n      inject: [...new Set(plugins.flatMap(plugin => plugin.inject || []))],\n      apply(ctx) { for (const plugin of plugins) plugin.apply(ctx); }\n    };\n  }\n});\n`;
await mkdir(new URL('dist/', root), { recursive: true });
await writeFile(new URL('dist/client.js', root), output);
console.log('Built Pocket Kit client from explicit feature and view sources.');
