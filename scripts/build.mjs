import { mkdir, readFile, writeFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
// Explicit allowlist: never scan the workspace or include .local/private files.
const entries = [
  ['home', 'client.js'],
  ['shortcuts', 'client.js'],
  ['network-speed', 'client-entry.js'],
  ['outing-checklist', 'client.js'],
  ['media', 'client.js'],
  ['utilities','client.js'],
  ['terminal-touch-keys','client.js'],
  ['aside-note', 'client.js'],
  ['csv-preview', 'client.js'],
];
const viewSources = Object.fromEntries(await Promise.all(['music', 'xiaoai'].map(async name => [name, await readFile(new URL(`features/${name}/view.js`, root), 'utf8')])));
const homeStartup = await readFile(new URL('features/home/startup.js', root), 'utf8');
const kitChrome = await readFile(new URL('features/shared/chrome.js', root), 'utf8');
const kitChromeUsers = new Set(['home', 'shortcuts', 'outing-checklist', 'media', 'utilities', 'terminal-touch-keys']);
const awaitedMessages = await readFile(new URL('features/utilities/messages.json',root),'utf8');
const utilityViews = Object.fromEntries(await Promise.all(['health','file-manager','beijing-pass','bill-manager'].map(async name=>[name,await readFile(new URL(`features/${name}/view.js`,root),'utf8')])));
const factories = [];
for (const [name, file] of entries) {
  let source = await readFile(new URL(`features/${name}/${file}`, root), 'utf8');
  if (kitChromeUsers.has(name)) {
    const marker = '/* KIT_CHROME */';
    if (source.split(marker).length !== 2) throw new Error(`Expected one kit chrome marker in ${name}`);
    source = source.replace(marker, () => kitChrome);
  }
  if (name === 'aside-note') {
    const model = (await readFile(new URL('features/aside-note/client-model.js', root), 'utf8')).replace(/^export /gm, '');
    source = source.replace('/* NOTES_MODEL */', () => model);
    const originalUi = await readFile(new URL('features/aside-note/original-ui.js', root), 'utf8');
    const originalCss = await readFile(new URL('features/aside-note/original.css', root), 'utf8');
    source = source.replace('/* NOTES_ORIGINAL_UI */', () => originalUi);
    source = source.replace("/* NOTES_ORIGINAL_CSS */ ''", () => JSON.stringify(originalCss));
  }
  if (name === 'terminal-touch-keys') {
    const engine=(await readFile(new URL('features/terminal-touch-keys/viewport.js',root),'utf8')).replace(/^export /gm,'');
    source=source.replace('/* TERMINAL_VIEWPORT */',()=>engine);
    const navigation=(await readFile(new URL('features/terminal-touch-keys/navigation.js',root),'utf8')).replace(/^export /gm,'');
    source=source.replace('/* TERMINAL_NAVIGATION */',()=>navigation);
  }
  if (name === 'home') {
    const marker = '/* HOME_STARTUP */';
    if (source.split(marker).length !== 2) throw new Error('Expected one home startup marker');
    source = source.replace(marker, () => homeStartup);
  }
  if (name === 'utilities') {
    source=source.replace('/* UTILITY_MESSAGES */',()=>JSON.stringify(JSON.parse(awaitedMessages)).slice(1,-1));
    for (const feature of ['health','file-manager','beijing-pass','bill-manager']) {
      const marker = `/* ${feature.toUpperCase().replaceAll('-','_')}_VIEW */`;
      source = source.replace(marker, () => utilityViews[feature]);
    }
  }
  if (name === 'media') {
    for (const feature of ['music', 'xiaoai']) {
      const marker = `/* ${feature.toUpperCase()}_VIEW */`;
      if (source.split(marker).length !== 2) throw new Error('Expected one view marker');
      source = source.replace(marker, () => viewSources[feature]);
    }
  }
  if (name === 'network-speed') {
    const marker = '/* MEASUREMENT_ENGINE */';
    if (source.split(marker).length !== 2) throw new Error('Expected one measurement marker');
    const engine = (await readFile(new URL('features/network-speed/measurement.js', root), 'utf8')).replace(/^export /gm, '');
    source = source.replace(marker, () => engine);
  }
  // Feature sources retain independently testable loader factories. The deployed
  // artifact registers only the aggregate module, not the legacy package IDs.
  const prefix = 'window.__ModuleLoader__.load(';
  if (!source.startsWith(prefix) || !source.trimEnd().endsWith(');')) throw new Error(`Invalid client factory: ${name}`);
  factories.push(`(${source.trimEnd().slice(prefix.length, -2)}).factory(require)`);
}
const output = `// Generated by npm run build. Edit features/, never this artifact.\nwindow.__ModuleLoader__.load({\n  id: '@local/pocket-kit',\n  factory(require) {\n    const plugins = [\n${factories.join(',\n')}\n    ];\n    return {\n      inject: [...new Set(plugins.flatMap(plugin => plugin.inject || []))],\n      apply(ctx) { for (const plugin of plugins) plugin.apply(ctx); }\n    };\n  }\n});\n`;
await mkdir(new URL('dist/', root), { recursive: true });
await writeFile(new URL('dist/client.js', root), output);
console.log('Built Pocket Kit client from explicit feature and view sources.');
